// ------------------------------------------------------------------
// Normalización (minúsculas, sin acentos) y morfología
// ------------------------------------------------------------------
const ACCENTS: Record<string, string> = {
  á: 'a', é: 'e', í: 'i', ó: 'o', ú: 'u', ü: 'u', ñ: 'n',
  Á: 'a', É: 'e', Í: 'i', Ó: 'o', Ú: 'u', Ü: 'u', Ñ: 'n',
};

export function normalizeEs(word: string): string {
  let out = '';
  for (const ch of word.toLowerCase()) {
    out += ACCENTS[ch] ?? ch;
  }
  return out;
}

// Caché de formas morfológicas ya resueltas (evita repetir el trabajo)
const morphCache = new Map<string, string>();

/**
 * Resuelve la forma canónica de una palabra española a partir de su base
 * en el diccionario: quita plurales (facturas→factura), género
 * (nueva→nuevo, registrada→registrado) y conjugaciones verbales
 * (creando→crear, creado→crear).
 */
function canonicalEs(word: string): string {
  if (WORDS_ES_EN[word]) return word;
  const hit = morphCache.get(word);
  if (hit !== undefined) return hit;

  let best = '';
  const candidates: string[] = [];

  // Plurales: -es / -s / -as / -os
  if (word.endsWith('es')) candidates.push(word.slice(0, -2));
  if (word.endsWith('s')) candidates.push(word.slice(0, -1));
  if (word.endsWith('as')) candidates.push(word.slice(0, -2));
  if (word.endsWith('os')) candidates.push(word.slice(0, -2));
  // Femenino: -a -> -o
  if (word.endsWith('a')) candidates.push(word.slice(0, -1) + 'o');
  // Verbos: -ando/-iendo -> -ar/-er/-ir; -ado/-ido/-ada/-ida -> -ar/-er/-ir
  if (word.endsWith('ando')) candidates.push(word.slice(0, -4) + 'ar');
  if (word.endsWith('iendo')) candidates.push(word.slice(0, -5) + 'er');
  if (word.endsWith('iendo')) candidates.push(word.slice(0, -5) + 'ir');
  if (word.endsWith('ado')) candidates.push(word.slice(0, -3) + 'ar');
  if (word.endsWith('ido')) candidates.push(word.slice(0, -3) + 'er');
  if (word.endsWith('ido')) candidates.push(word.slice(0, -3) + 'ir');
  if (word.endsWith('ada')) candidates.push(word.slice(0, -3) + 'ar');
  if (word.endsWith('ida')) candidates.push(word.slice(0, -3) + 'er');
  if (word.endsWith('ida')) candidates.push(word.slice(0, -3) + 'ir');
  if (word.endsWith('ados')) candidates.push(word.slice(0, -4) + 'ar');
  if (word.endsWith('idos')) candidates.push(word.slice(0, -4) + 'er');
  if (word.endsWith('idas')) candidates.push(word.slice(0, -4) + 'er');
  if (word.endsWith('adas')) candidates.push(word.slice(0, -4) + 'ar');
  // Tercera persona: crea->crear, registra->registrar, valida->validar
  if (word.endsWith('a') && word.length > 4) candidates.push(word + 'r');
  if (word.endsWith('e') && word.length > 4) candidates.push(word + 'r');
  // Infinitivo con pronombre: registrarse->registrar
  if (word.endsWith('se') && word.length > 5) candidates.push(word.slice(0, -2));

  for (const c of candidates) {
    if (WORDS_ES_EN[c]) {
      best = c;
      break;
    }
  }
  morphCache.set(word, best);
  return best;
}

// ------------------------------------------------------------------
// Preservación de mayúsculas
// ------------------------------------------------------------------
function applyCase(source: string, translation: string): string {
  if (source.length === 0 || translation.length === 0) return translation;
  const hasUpper = /[A-Z]/.test(source);
  if (!hasUpper) return translation;
  // TODO mayúsculas (TÍTULO -> TITLE)
  if (source === source.toUpperCase() && /[A-Za-z]/.test(source)) {
    return translation.toUpperCase();
  }
  // Primera letra en mayúscula (Título -> Title)
  if (/^[A-Z]/.test(source)) {
    return translation.charAt(0).toUpperCase() + translation.slice(1);
  }
  return translation;
}

// ------------------------------------------------------------------
// Frases: mapa normalizado -> traducción, ordenadas por longitud
// ------------------------------------------------------------------
const PHRASE_MAP = new Map<string, string>();
const PHRASE_KEYS: string[] = [];
// Frases de UI + frases multi-palabra del diccionario de palabras
for (const key of Object.keys(UI_PHRASES_ES_EN)) {
  const norm = normalizeEs(key.trim());
  PHRASE_MAP.set(norm, UI_PHRASES_ES_EN[key]);
  PHRASE_KEYS.push(norm);
}
for (const key of Object.keys(WORDS_ES_EN)) {
  if (key.includes(' ')) {
    const norm = normalizeEs(key.trim());
    if (!PHRASE_MAP.has(norm)) {
      PHRASE_MAP.set(norm, WORDS_ES_EN[key]);
      PHRASE_KEYS.push(norm);
    }
  }
}
// De mayor a menor número de palabras (longest match)
PHRASE_KEYS.sort((a, b) => b.split(' ').length - a.split(' ').length);

// Índice por primera letra para búsqueda O(1) en el walker
const EMPTY: string[] = [];
const PHRASE_INDEX = new Map<string, string[]>();
for (const key of PHRASE_KEYS) {
  const first = key.charAt(0);
  const arr = PHRASE_INDEX.get(first);
  if (arr) arr.push(key);
  else PHRASE_INDEX.set(first, [key]);
}

const WORD_MAP = new Map<string, string>();
for (const key of Object.keys(WORDS_ES_EN)) {
  WORD_MAP.set(normalizeEs(key.trim()), WORDS_ES_EN[key]);
}

/**
 * Traduce un texto español a inglés.
 * - Primero intenta frases completas (longest match).
 * - Luego palabra por palabra con normalización morfológica.
 * - Conserva números, puntuación y palabras desconocidas.
 */
function translateWord(word: string): string | null {
  const wNorm = normalizeEs(word);
  const direct = WORD_MAP.get(wNorm);
  if (direct) return direct;
  // Palabras de una sola palabra guardadas en el diccionario de frases
  // (p. ej. 'olvido', 'seguro') también deben resolverse aquí.
  const phraseHit = PHRASE_MAP.get(wNorm);
  if (phraseHit && !wNorm.includes(' ')) return phraseHit;
  const canon = canonicalEs(wNorm);
  if (canon) {
    const canonWord = WORD_MAP.get(canon);
    if (canonWord) return canonWord;
    const canonPhrase = PHRASE_MAP.get(canon);
    if (canonPhrase && !canon.includes(' ')) return canonPhrase;
  }
  if (EN_SKIP.has(word.toLowerCase())) return word;
  return null;
}

/**
 * Traduce un texto español a inglés.
 * Camina por la cadena original, aplicando longest-match de frases en
 * cualquier posición y, donde no hay frase, traducción palabra por palabra.
 * Preserva números, puntuación y palabras desconocidas.
 */
export function translateToEnglish(input: string): string {
  if (!input || typeof input !== 'string') return input;
  // Preserva el espacio al inicio/fin (p. ej. 'Cliente: ' o ' - Total')
  const m = input.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!m) return input;
  const lead = m[1];
  const trimmed = m[2];
  const trail = m[3];
  if (!trimmed) return input;

  const norm = normalizeEs(trimmed);
  const out: string[] = [];
  let i = 0;
  const n = norm.length;

  while (i < n) {
    const ch = norm[i];
    // Intentar frase más larga que comience en i (frontera de palabra)
    let matchedPhrase: string | null = null;
    const candidates = PHRASE_INDEX.get(ch) ?? EMPTY;
    for (const phrase of candidates) {
      if (norm.startsWith(phrase, i)) {
        // Verificar fronteras de palabra
        const beforeOk = i === 0 || /\s/.test(norm[i - 1]);
        const afterIdx = i + phrase.length;
        const afterOk = afterIdx >= n || /[\s:;,.!?)\]/]/.test(norm[afterIdx]);
        if (beforeOk && afterOk) {
          matchedPhrase = phrase;
          break;
        }
      }
    }

    if (matchedPhrase) {
      const len = matchedPhrase.length;
      const original = trimmed.slice(i, i + len);
      const phraseValue = PHRASE_MAP.get(matchedPhrase)!;
      // Aplicar mayúsculas palabra por palabra (Título -> Title Case)
      const origWords = original.split(' ');
      const valWords = phraseValue.split(' ');
      if (origWords.length === valWords.length) {
        out.push(origWords.map((w, k) => applyCase(w, valWords[k])).join(' '));
      } else {
        out.push(applyCase(original, phraseValue));
      }
      i += len;
      continue;
    }

    // Token actual: palabra con puntuación adjunta, o no-letras (números, espacios)
    if (/[A-Za-z]/.test(ch)) {
      let j = i;
      while (j < n && /[A-Za-z]/.test(norm[j])) j++;
      const word = trimmed.slice(i, j);
      const translated = translateWord(word);
      if (translated) {
        out.push(applyCase(word, translated));
      } else {
        out.push(word); // desconocida: se conserva
      }
      i = j;
    } else {
      out.push(trimmed[i]);
      i++;
    }
  }

  return lead + out.join('') + trail;
}

export function isEnglishLocale(locale: string): boolean {
  return locale === 'en_US' || locale === 'en' || locale.startsWith('en');
}


